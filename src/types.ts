/**
 * A Figure is everything one historical person's phone shows.
 * Components never hard-code a person: they read only from this shape.
 *
 * The phone shows only original text. Everything that explains it lives in a
 * Gloss and appears on the 白話註釋 page, opened from a button.
 */
export type Source = string;

/** Explanation of one piece of original text, shown only on the 白話註釋 page. */
export interface Gloss {
  /** Provenance, e.g. "原文 · 〈初到黃州〉（節錄）". */
  src?: Source;
  /** 白話: a modern-language rendering. */
  plain?: string;
  /** 註釋: context, word glosses, dating caveats. */
  notes?: string[];
}

export interface Figure {
  id: string;
  name: string; // 蘇軾
  /** The frozen moment. Everything is written "as of" this instant. */
  moment: {
    dateLine: string; // 元豐三年 二月初一  (lock screen, above the clock)
    clock: string; // 15:42  (status bar + lock screen)
    weatherLine: string; // 黃州 9° 小雨 · 申時
  };
  lockNotifications: LockNotification[];
  home: {
    weather: { place: string; temp: string; condition: string; quote: string };
    calendar: { month: string; day: string; events: { title: string; sub?: string; color: string }[] };
  };
  threads: Thread[];
  /** 我的名片: the figure's own card, pinned at the top of 通訊錄. */
  me: Contact;
  contacts: Contact[];
  photos: Photo[];
  map: MapData;
  wallet: WalletData;
  notes: Note[];
  /** Shown under the 圖庫 title, e.g. 元豐二年七月至三年二月 */
  photosRange: string;
  /** Footnote under the photo grid explaining the conceit. */
  photosFootnote: string;
}

export interface LockNotification {
  app: 'messages' | 'wallet' | 'calendar';
  title: string;
  time: string;
  body: string;
  /** Thread id to open when tapped (messages only). */
  threadId?: string;
}

export type Message = (
  | { kind: 'system'; text: string } // centered timestamp/divider ("粗體 · 細字") or a line of narration
  | { kind: 'in' | 'out'; text: string; /** Sender name, for incoming messages in a group thread. */ from?: string }
) &
  Gloss;

export interface Thread {
  id: string;
  name: string;
  avatar: string; // one character, used when no contact portrait applies
  /** Group threads: contact ids whose portraits make up the group avatar. */
  members?: string[];
  when: string; // shown in the list
  unread?: boolean;
  messages: Message[];
}

/**
 * An imagined portrait: an AI-generated gongbi painting, not a likeness.
 * Generated by scripts/gen-portraits.py from scripts/portraits/<figure>.json.
 * Every visible trait (hat, prop, expression) needs a basis, given in `why`.
 */
export interface Portrait {
  /** Path under public/, relative to the page (the build uses base ./), e.g. portraits/sushi/ziyou.webp */
  image: string;
  /** Basis for the traits, listed on the 註釋 page. */
  why?: string;
  /** Grey the portrait out (the person has died). */
  faded?: boolean;
}

/**
 * A 通訊錄 entry. `memo` (備註) is the one place where invented wording is
 * allowed: the figure's own note on this person, as of the frozen moment,
 * every claim in it grounded in fact. Its `notes` give the basis.
 */
export interface Contact extends Gloss {
  id: string;
  name: string;
  avatar: string; // one character, the fallback when there is no portrait
  portrait?: Portrait;
  /** Under the name, e.g. 字子由 · 弟弟 */
  subtitle: string;
  /** Section in the list, e.g. 家人 / 朋友 / 御史臺. */
  group: string;
  fields: { label: string; value: string; tone?: 'link' | 'danger' | 'muted' }[];
  memo?: string;
  /** Thread opened by the 訊息 button; the thread header links back here. */
  threadId?: string;
  /** Shown as a small status line: 已故, 已封鎖… */
  status?: string;
}

export interface Photo extends Gloss {
  glyph: string; // one character standing in for the image
  title: string;
  place: string;
  date: string;
  bg: string;
  fg: string;
  /** Caption: an original passage about this moment. */
  desc: string;
}

export interface MapData {
  title: string; // 前往黃州
  subtitle: string;
  /** Map is a 393×852 SVG; coordinates are in that space (top ~470px visible above the sheet). */
  rivers: { name: string; path: string; labelX: number; labelY: number; width: number }[];
  /** Earlier leg drawn as grey dots (e.g. the arrest journey). */
  priorRoute: string;
  /** The active route, drawn in system blue. */
  route: string;
  places: { name: string; x: number; y: number; major?: boolean; destination?: boolean; origin?: boolean }[];
  stops: { name: string; date: string; note: string }[];
  /** Index into stops selected by default. */
  defaultStop: number;
}

export interface WalletData {
  /** Background cards, back to front. */
  backCards: { title: string; right: string; gradient: [string, string] }[];
  main: {
    title: string;
    monthlyTotal: number;
    dailyAllowance: number;
    parts: number;
    footer: [string, string];
    gradient: [string, string];
  };
  takeLabel: string;
  takenLabel: string;
  transactions: { badge: string; color: string; title: string; sub: string; amount: string }[];
  /** The original passage the wallet is built on. */
  quote?: { text: string } & Gloss;
}

export interface Note extends Gloss {
  title: string;
  preview: string;
  header: string; // centered date line inside the note
  checklist?: { text: string; done?: boolean }[];
  body?: string; // preformatted text, \n preserved
}
